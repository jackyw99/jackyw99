DISTRICT_RE = re.compile(r"新竹[市縣]([一-鿿]{1,3}[區鄉鎮市])")


def district(addr):
    m = DISTRICT_RE.search(addr)
    return m.group(1) if m else ""


def has_parking(parking):
    return "有車位" in parking


HEADER = ["編號", "標題", "社區", "地址", "行政區", "成交總價(萬)",
          "成交單價(萬/坪)", "樓層", "屋齡", "建物坪數", "車位"]

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(BASE, "data")
STEM = "hsinchu-transactions-2026-05-26_06-01"


def write_csv():
    path = os.path.join(DATA, STEM + ".csv")
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        for (n, title, comm, addr, total, unit, floor, age, area, parking) in ROWS:
            w.writerow([n, title, comm, addr, district(addr), total, unit,
                        floor, age, area, parking])
    return path


def write_md():
    path = os.path.join(DATA, STEM + ".md")
    totals = [r[4] for r in ROWS]
    n = len(ROWS)
    avg_total = sum(totals) / n
    with_park = sum(1 for r in ROWS if has_parking(r[9]))
    # 行政區統計
    counts = {}
    for r in ROWS:
        d = district(r[3]) or "其他"
        counts[d] = counts.get(d, 0) + 1
    lines = []
    lines.append("# 新竹成交資訊 2026/05/26 ~ 2026/06/01")
    lines.append("")
    lines.append("> 建坪扣除車位（單價為概抓，會因所扣除之車位價格差異而有所不同）。")
    lines.append("> 資料僅供內部參考，**請勿外傳**。")
    lines.append("")
    lines.append("## 摘要")
    lines.append("")
    lines.append(f"- 筆數：{n} 筆")
    lines.append(f"- 平均成交總價：約 {avg_total:.0f} 萬")
    lines.append(f"- 最高總價：{max(totals)} 萬｜最低總價：{min(totals)} 萬")
    lines.append(f"- 含車位物件：{with_park} 筆｜無車位物件：{n - with_park} 筆")
    lines.append("")
    lines.append("### 行政區分布")
    lines.append("")
    lines.append("| 行政區 | 筆數 |")
    lines.append("| --- | ---: |")
    for d, c in sorted(counts.items(), key=lambda x: -x[1]):
        lines.append(f"| {d} | {c} |")
    lines.append("")
    lines.append("## 成交明細")
    lines.append("")
    lines.append("| # | 標題 | 社區 | 地址 | 行政區 | 總價(萬) | 單價(萬/坪) | 樓層 | 屋齡 | 建物(坪) | 車位 |")
    lines.append("| ---: | --- | --- | --- | --- | ---: | ---: | --- | --- | ---: | --- |")
    for (no, title, comm, addr, total, unit, floor, age, area, parking) in ROWS:
        t = title.replace("|", "｜")
        a = addr.replace("|", "｜")
        c = comm.replace("|", "｜")
        lines.append(f"| {no} | {t} | {c} | {a} | {district(addr)} | "
                     f"{total} | {unit} | {floor} | {age} | {area:.3f} | {parking} |")
    lines.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return path


